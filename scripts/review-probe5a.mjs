import { mkdirSync } from "node:fs";
import { chromium } from "playwright";
const WEB = "http://localhost:8288", OUT = process.env.OUT_DIR, CASE = process.env.CASE;
const ZIP = "C:/Users/franc/Desktop/tesis/caso-2001-estudio.zip";
mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1366, height: 768 } });
const page = await ctx.newPage();
const log = (...a) => console.log(...a);
const posts = [], issues = [];
page.on("console", (m) => { if (m.type() === "error") issues.push(m.text().slice(0, 200)); });
page.on("request", (r) => { if (r.method() !== "GET" && /8280/.test(r.url())) posts.push(`${r.method()} ${r.url().replace(/^https?:\/\/[^/]+/, "")}`); });
await page.goto(`${WEB}/`, { waitUntil: "networkidle" });
await page.getByRole("button", { name: /Entrar con doctor demo/ }).click();
await page.getByRole("button", { name: "Nuevo estudio" }).waitFor();
const body = async () => (await page.locator("main").first().innerText()).replace(/\n+/g, " | ");
await page.getByRole("button", { name: "Nuevo estudio" }).click();
await page.getByRole("heading", { name: "Nuevo estudio", level: 1 }).waitFor();
await page.getByLabel("Buscar paciente por código o nombre").fill("VIS-006857");
await page.getByRole("list", { name: "Resultados de pacientes" }).getByRole("button").first().click();
await page.getByPlaceholder("CASE-XXXX").fill("ID con espacios!");
log("ID inválido →", (await page.locator("#ns-run-hint, .wl-field-error").allInnerTexts()).join(" / "));
await page.getByPlaceholder("CASE-XXXX").fill(CASE);
await page.getByLabel(/Fecha del estudio/).fill("2026-10-14");
await page.screenshot({ path: `${OUT}/c1.png` });
await page.getByRole("button", { name: "Continuar", exact: true }).click();
await page.waitForTimeout(800);
log("PASO 2 inicial:", (await body()).slice(0, 700));
log("hint:", await page.locator("#ns-run-hint").innerText());
await page.screenshot({ path: `${OUT}/c2a.png` });
// Atrás y adelante
await page.getByRole("button", { name: "Atrás", exact: true }).click();
await page.waitForTimeout(500);
log("Atrás conserva ID:", await page.getByPlaceholder("CASE-XXXX").inputValue(), "| fecha:", await page.getByLabel(/Fecha del estudio/).inputValue());
await page.getByRole("button", { name: "Continuar", exact: true }).click();
await page.locator('.ns-zip input[type="file"]').setInputFiles(ZIP);
await page.getByText(/series detectadas/).waitFor({ timeout: 120000 });
await page.screenshot({ path: `${OUT}/c2b.png` });
log("PASO 2 con ZIP:", (await body()).slice(0, 1000));
await page.getByRole("button", { name: "Continuar", exact: true }).click();
await page.getByRole("heading", { name: "Contexto y revisión", level: 2 }).waitFor();
await page.waitForTimeout(500);
log("PASO 3:", (await body()).slice(0, 1400));
await page.screenshot({ path: `${OUT}/c3.png` });
await page.getByRole("button", { name: "Atrás", exact: true }).click();
await page.waitForTimeout(500);
log("Atrás desde 3 conserva ZIP:", /series detectadas/.test(await body()));
await page.getByRole("button", { name: "Continuar", exact: true }).click();
await page.getByRole("heading", { name: "Contexto y revisión", level: 2 }).waitFor();
// Cancelar con datos
await page.getByRole("button", { name: "Cancelar", exact: true }).click();
await page.waitForTimeout(500);
log("Cancelar con datos →", (await page.locator("[role=alert]").allInnerTexts()).join(" | ").slice(0, 300));
await page.screenshot({ path: `${OUT}/c-cancel.png` });
await page.getByRole("button", { name: /Seguir editando/ }).click();
// Doble clic en Analizar
const before = posts.length;
const analyze = page.getByRole("button", { name: "Analizar estudio", exact: true });
await analyze.dblclick();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/c-procesando.png` });
log("procesando:", (await body()).slice(0, 500));
await page.waitForURL(new RegExp(`/estudio/${CASE}`), { timeout: 900000 });
await page.locator("aside.rr-panel").waitFor();
log("POSTs desde el doble clic:", posts.slice(before).filter((p) => /run|analysis|product/i.test(p)));
log("todas las escrituras:", posts.join(" ; ").slice(0, 900));
log("errores:", issues);
await browser.close();
