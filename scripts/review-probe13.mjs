import { chromium } from "playwright";
const WEB = "http://localhost:8288", CASE = process.env.CASE;
if (!/^REVFIN-/.test(CASE ?? "")) throw new Error("solo caso propio");
const browser = await chromium.launch({ headless: true });
const page = await (await browser.newContext({ viewport: { width: 1366, height: 768 } })).newPage();
const log = (...a) => console.log(...a);
const writes = []; const dialogs = [];
page.on("dialog", async (d) => { dialogs.push(`${d.type()}: ${d.message().slice(0, 160)}`); await d.dismiss(); });
page.on("request", (r) => { if (r.method() !== "GET" && /8280/.test(r.url())) writes.push(`${r.method()} ${r.url().replace(/^https?:\/\/[^/]+/, "")}`); });
await page.goto(`${WEB}/`, { waitUntil: "networkidle" });
await page.getByRole("button", { name: /Entrar con doctor demo/ }).click();
await page.getByRole("button", { name: "Nuevo estudio" }).waitFor();
await page.goto(`${WEB}/estudio/${CASE}`, { waitUntil: "networkidle" });
await page.locator("aside.rr-panel").waitFor({ timeout: 90000 }); await page.waitForTimeout(2500);
await page.getByRole("tab", { name: "Revisión" }).click();
await page.getByTestId("prepare-prereport").click();
await page.getByTestId("prereport-summary").waitFor({ timeout: 30000 });
await page.waitForTimeout(1500);
await page.getByTestId("prereport-observations").fill("Observación sin guardar de prueba");
await page.waitForTimeout(500);
log("barra tras editar:", (await page.locator(".pre-bar").innerText()).replace(/\n+/g, " | "));
await page.getByTestId("prereport-close").click();
await page.waitForTimeout(800);
log("diálogos nativos al cerrar con cambios:", dialogs, "| editor sigue abierto:", await page.getByTestId("prereport-editor").count());
log("texto de otros diálogos:", (await page.locator("[role=alertdialog]").allInnerTexts()).join("|"));
log("escrituras:", writes);
await browser.close();
