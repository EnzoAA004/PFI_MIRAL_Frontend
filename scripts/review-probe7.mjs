import { mkdirSync } from "node:fs";
import { chromium } from "playwright";
const WEB = "http://localhost:8288", OUT = process.env.OUT_DIR;
mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1366, height: 768 } });
const page = await ctx.newPage();
const log = (...a) => console.log(...a);
const writes = [], issues = [];
page.on("console", (m) => { if (m.type() === "error") issues.push(m.text().slice(0, 200)); });
await page.route(/localhost:8280\/api\/(?!auth)/, (route) => { const r = route.request(); if (r.method() === "GET") return route.continue(); writes.push(`${r.method()} ${r.url().replace(/^https?:\/\/[^/]+/, "")}`); return route.abort(); });
await page.goto(`${WEB}/`, { waitUntil: "networkidle" });
await page.getByRole("button", { name: /Entrar con doctor demo/ }).click();
await page.getByRole("button", { name: "Nuevo estudio" }).waitFor();
const tools = page.locator("[aria-label='Herramientas del estudio']");
const text = async () => (await tools.innerText().catch(() => "—")).replace(/\n+/g, " | ");
await page.goto(`${WEB}/estudio/OSF-ID10-V2-T1`, { waitUntil: "networkidle" });
await page.locator("aside.rr-panel").waitFor({ timeout: 90000 }); await page.waitForTimeout(2500);
await page.getByTestId("tools-open").click();
await page.locator('[data-tool-id="comparison"]').click();
await page.waitForTimeout(1500);
await tools.locator("select").first().selectOption({ index: 1 });
await page.waitForTimeout(3500);
log("PANEL con referencia V1-T1:", (await text()).slice(0, 2500));
await page.screenshot({ path: `${OUT}/cmp-panel.png` });
// cambio rápido de referencia
await tools.locator("select").first().selectOption({ index: 2 });
await tools.locator("select").first().selectOption({ index: 3 });
await page.waitForTimeout(3500);
log("tras cambio rápido →", (await text()).slice(0, 500));
await tools.locator("select").first().selectOption({ index: 1 });
await page.waitForTimeout(3000);
await page.getByTestId("open-dual-comparison").click();
await page.waitForTimeout(6000);
log("VISUAL:", (await page.locator("body").innerText()).replace(/\n+/g, " | ").slice(0, 2500));
await page.screenshot({ path: `${OUT}/cmp-dual.png` });
log("botones:", (await page.getByRole("button").allInnerTexts()).filter(Boolean).join(" / ").slice(0, 900));
log("escrituras bloqueadas:", writes, "errores:", issues);
await browser.close();
