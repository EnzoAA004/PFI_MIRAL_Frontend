import { mkdirSync } from "node:fs";
import { chromium } from "playwright";
const WEB = "http://localhost:8288", OUT = process.env.OUT_DIR;
mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1366, height: 768 } });
const page = await ctx.newPage();
const log = (...a) => console.log(...a);
const aborted = [], issues = [];
page.on("console", (m) => { if (m.type() === "error") issues.push(m.text().slice(0, 160)); });
await page.route(/localhost:8280\/api\/(?!auth)/, (route) => { const r = route.request(); if (r.method() === "GET") return route.continue(); aborted.push(`${r.method()} ${r.url().replace(/^https?:\/\/[^/]+/, "")}`); return route.abort(); });
await page.goto(`${WEB}/`, { waitUntil: "networkidle" });
await page.getByRole("button", { name: /Entrar con doctor demo/ }).click();
await page.getByRole("button", { name: "Nuevo estudio" }).waitFor();
await page.waitForTimeout(1500);
const estado = page.locator("select").filter({ has: page.locator("option", { hasText: "Pendiente" }) }).first();
await estado.selectOption({ label: "Finalizado (1)" });
await page.waitForTimeout(700);
log("Finalizado →", await page.locator("tbody tr").count(), "filas;", (await page.locator("h1,h2").first().innerText()).replace(/\s+/g, " "));
const row = page.locator("tbody tr").first();
log("fila:", (await row.innerText()).replace(/\s+/g, " "));
await row.click();
await page.waitForTimeout(800);
await page.screenshot({ path: `${OUT}/p1-seleccion.png` });
await page.getByRole("button", { name: "Abrir estudio" }).click();
await page.locator("aside.rr-panel").waitFor({ timeout: 60000 }).catch(() => log("NO abrió el visor"));
await page.waitForTimeout(2500);
log("url:", page.url());
const back = page.getByRole("button", { name: /Estudios/ }).first();
log("botón volver:", await back.count());
await back.click();
await page.waitForTimeout(1200);
log("regreso → url", page.url(), "| filas:", await page.locator("tbody tr").count(), "| filtro estado:", await estado.inputValue().catch(() => "?"));
await page.goBack(); await page.waitForTimeout(1500);
log("atrás del navegador → url", page.url());
await page.goForward(); await page.waitForTimeout(1500);
log("adelante → url", page.url(), "| cierra a lista con:", await page.locator("tbody tr").count());
log("aborted", aborted, "errores", issues);
await browser.close();
