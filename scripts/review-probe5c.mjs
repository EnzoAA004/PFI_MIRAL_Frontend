import { mkdirSync } from "node:fs";
import { chromium } from "playwright";
const WEB = "http://localhost:8288", OUT = process.env.OUT_DIR, CASE = process.env.CASE;
if (!/^REVFIN-/.test(CASE ?? "")) throw new Error("solo sobre el caso propio REVFIN-*");
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1366, height: 768 } });
const page = await ctx.newPage();
const log = (...a) => console.log(...a);
const writes = [], issues = [];
page.on("console", (m) => { if (m.type() === "error") issues.push(m.text().slice(0, 200)); });
page.on("request", (r) => { if (r.method() !== "GET" && /8280/.test(r.url())) writes.push(`${r.method()} ${r.url().replace(/^https?:\/\/[^/]+/, "")}`); });
const panel = async () => (await page.locator("aside.rr-panel").innerText()).replace(/\n+/g, " | ");
const open = async () => {
  await page.goto(`${WEB}/estudio/${CASE}`, { waitUntil: "networkidle" });
  await page.locator("aside.rr-panel").waitFor({ timeout: 90000 });
  await page.waitForTimeout(2500);
  await page.getByRole("tab", { name: "Revisión" }).click();
};
await page.goto(`${WEB}/`, { waitUntil: "networkidle" });
await page.getByRole("button", { name: /Entrar con doctor demo/ }).click();
await page.getByRole("button", { name: "Nuevo estudio" }).waitFor();
await open();
await page.locator("aside.rr-panel select").last().selectOption({ label: "Finalizado" });
await page.getByRole("button", { name: "Finalizar y aprobar estudio", exact: true }).click();
await page.waitForTimeout(3000);
log("tras finalizar · pie:", (await page.locator(".rr-review-footer").innerText()).replace(/\n+/g, " | "));
log("barra:", (await page.locator("header, [class*=topbar]").first().innerText()).replace(/\n+/g, " ").slice(0, 220));
log("diálogos:", (await page.locator("[role=alertdialog],[role=dialog]").allInnerTexts()).join("|").slice(0, 300));
await page.screenshot({ path: `${OUT}/r-fin-despues.png` });
await open();
log("RECARGA → estado:", await page.locator("aside.rr-panel select").last().inputValue(), "| notas:", await page.getByPlaceholder(/Observaciones generales/).inputValue(), "| pie:", (await page.locator(".rr-review-footer").innerText()).replace(/\n+/g, " | "));
log("controles:", await page.locator("aside.rr-panel textarea, aside.rr-panel select, aside.rr-panel input").evaluateAll((els) => els.map((e) => `${e.tagName}${e.disabled ? ":disabled" : ""}`)));
await page.getByRole("tab", { name: "Resultados" }).click();
await page.locator(".rr-level", { hasText: "L4-L5" }).first().click();
log("medición editable tras finalizar:", await page.locator(".rr-measure-input").first().isDisabled().catch(() => "sin input"));
await page.screenshot({ path: `${OUT}/r-fin-recarga.png` });
await page.getByRole("tab", { name: "Revisión" }).click();
log("Preparar preinforme habilitado:", await page.getByTestId("prepare-prereport").isEnabled());
log("escrituras:", writes.join(" ; "));
log("errores:", issues);
await browser.close();
